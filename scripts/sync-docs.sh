#!/usr/bin/env bash
#
# sync-docs.sh — pull the SPECIFIC backend reference docs this repo depends on (as pharos-web).
#
# fertility-grove-backend is the single source of truth for the shared reference docs:
#   prd.md, api-handoff.md, implementation-plan.md
# This copies EXACTLY those (an explicit allowlist — see FILES below) from the backend's `dev`
# branch, and nothing else.
#
# This repo files them by subject rather than by the backend's layout:
#   docs/prd/  — prd.md and the backend's implementation plan
#   docs/api/  — api-handoff.md and swagger.json
# FILES maps each backend path to its local one, so a move on either side is a one-line change.
#
# It deliberately does NOT mirror the whole backend docs/ folder, and it never deletes: the sync
# only ever WRITES the allowlisted paths, so web-only docs in this repo's docs/ (po-questions.md,
# backend-tasks.md, the Figma inventories, the local PRD .docx) are left untouched. If the backend
# renames or drops one of the files, the copy fails loudly here instead of silently going stale.
#
# swagger.json is generated by the running API (not committed to the backend repo), so it's fetched
# from the live endpoint (SWAGGER_URL), not the clone.
#
# It does a shallow, sparse, blobless clone of ONLY the docs/ folder into a temp dir, copies the
# allowlisted files to their mapped paths, then refreshes swagger.json.
#
# Usage:  ./scripts/sync-docs.sh [branch]   (branch defaults to "dev")
#   env overrides: REMOTE=<git-url>  SUBDIR=<path>  SWAGGER_URL=<url>  WEB_DOCS=<dir>
set -euo pipefail

REMOTE="${REMOTE:-git@github.com:groksmith/fertility-grove-backend.git}"
BRANCH="${1:-${BRANCH:-dev}}"
SUBDIR="${SUBDIR:-docs}"
SWAGGER_URL="${SWAGGER_URL:-https://api.fertilitygrove.click/swagger/v1/swagger.json}"

# The ONLY files mirrored from the backend repo, as "<backend path>:<local path>", each relative to
# its repo's docs/. swagger.json is intentionally NOT here — it's fetched from the live API below,
# into SWAGGER_DEST. Add a pair to vendor another backend doc; nothing else is pulled.
FILES=(
  "prd.md:prd/prd.md"
  "implementation-plan.md:prd/implementation-plan.md"
  "api-handoff.md:api/api-handoff.md"
)
SWAGGER_DEST="api/swagger.json"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WEB_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
WEB_DOCS="${WEB_DOCS:-$WEB_ROOT/docs}"

TMP_DIR="$(mktemp -d)"
cleanup() { rm -rf "$TMP_DIR"; }
trap cleanup EXIT

echo "Fetching $SUBDIR/ from $REMOTE ($BRANCH)…"
git clone --quiet --depth 1 --filter=blob:none --sparse --branch "$BRANCH" \
  "$REMOTE" "$TMP_DIR/repo"
git -C "$TMP_DIR/repo" sparse-checkout set "$SUBDIR"

SRC="$TMP_DIR/repo/$SUBDIR"
if [ ! -d "$SRC" ]; then
  echo "error: '$SUBDIR/' not found on '$BRANCH' of $REMOTE" >&2
  exit 1
fi

# Copy EXACTLY the allowlisted files. A missing source is a hard error so an upstream rename
# surfaces here rather than leaving a stale copy behind.
mkdir -p "$WEB_DOCS"
for pair in "${FILES[@]}"; do
  from="${pair%%:*}"
  to="${pair#*:}"
  if [ ! -f "$SRC/$from" ]; then
    echo "error: expected '$SUBDIR/$from' not found on '$BRANCH' of $REMOTE" >&2
    exit 1
  fi
  mkdir -p "$WEB_DOCS/$(dirname "$to")"
  cp "$SRC/$from" "$WEB_DOCS/$to"
  echo "  ✓ docs/$to"
done

# swagger.json is produced by the running API (not committed to the backend repo), so refresh it
# straight from the live endpoint. Download to a temp file, validate it parses as JSON, then write it
# in with a single trailing newline (the endpoint omits one) to keep diffs stable.
echo "Fetching swagger.json from $SWAGGER_URL …"
SWAGGER_TMP="$TMP_DIR/swagger.json"
curl -fsSL "$SWAGGER_URL" -o "$SWAGGER_TMP"
if command -v jq >/dev/null 2>&1; then
  jq -e . "$SWAGGER_TMP" >/dev/null
else
  node -e 'JSON.parse(require("fs").readFileSync(process.argv[1], "utf8"))' "$SWAGGER_TMP"
fi
mkdir -p "$WEB_DOCS/$(dirname "$SWAGGER_DEST")"
cp "$SWAGGER_TMP" "$WEB_DOCS/$SWAGGER_DEST"
[ -n "$(tail -c1 "$WEB_DOCS/$SWAGGER_DEST")" ] && printf '\n' >>"$WEB_DOCS/$SWAGGER_DEST"
echo "  ✓ docs/$SWAGGER_DEST"

echo "Synced ${#FILES[@]} docs + swagger.json from $REMOTE ($BRANCH)"
echo
echo "Changes (git status):"
git -C "$WEB_ROOT" status --short docs
